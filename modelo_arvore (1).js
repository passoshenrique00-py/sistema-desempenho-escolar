function preverDesempenho(ano, frequencia, usoIA) {

    // Dados informados pelo usuário
    const entrada = [ano, frequencia, usoIA];

    // Aplicando o mesmo StandardScaler usado no treinamento
    const entradaPadronizada = entrada.map(
        (valor, i) => (valor - scalerMean[i]) / scalerScale[i]
    );

    // Percorrendo a Árvore de Decisão
    let no = 0;

    while (treeLeft[no] !== -1) {

        const feature = treeFeature[no];
        const threshold = treeThreshold[no];

        if (entradaPadronizada[feature] <= threshold) {
            no = treeLeft[no];
        } else {
            no = treeRight[no];
        }
    }

    // Obtendo os valores da folha
    const valores = treeValue[no][0];

    // Classe com maior quantidade de exemplos
    const classe = valores[1] > valores[0] ? 1 : 0;

    return classe;
}
